#!/usr/bin/env python3
"""Compile packed IMA decoder transitions from the encoder's step table."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    source = (ROOT / 'tools/encode_native_audio.cpp').read_text()
    def array(name):
        match = re.search(r'const int ' + name + r'\[\]=\{([^}]+)\}', source)
        if match is None:
            raise ValueError('Missing IMA encoder table: ' + name)
        return [int(v) for v in match[1].split(',')]
    steps, changes = array('steps'), array('changes')
    if len(steps) != 89 or len(changes) != 8:
        raise ValueError('Unexpected IMA table dimensions')
    table = []
    for index, step in enumerate(steps):
        for code in range(16):
            delta = (step >> 3) + (step if code & 4 else 0)
            delta += (step >> 1) if code & 2 else 0
            delta += (step >> 2) if code & 1 else 0
            if code & 8:
                delta = -delta
            next_index = max(0, min(88, index + changes[code & 7]))
            table.append((delta & 0x3ffff) | (next_index << 18))
    out = ROOT / 'generated/audio_ima_fast.h'
    out.parent.mkdir(exist_ok=True)
    out.write_text('/* Generated by tools/build_audio_ima_fast.py; signed 18-bit delta + 7-bit index. */\n'
                   'static const uint32_t audio_ima_fast[1424]={' + ','.join(map(str, table)) + '};\n')


if __name__ == '__main__':
    main()
