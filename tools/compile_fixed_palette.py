#!/usr/bin/env python3
"""Compile the exact RGB555 -> compact HUD palette nearest-color mapping.

Read the authored compact palette from fixed_object.c, including its order.
Strictly smaller distance wins, so equal distances retain the first index.
Index zero is transparent and is never a candidate for an opaque color.
"""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(check=False):
    source = (ROOT / 'src/fixed_object.c').read_text()
    # Palette setup may live in a cold helper to fit the IWRAM overlay.
    # Require one unambiguous authored palette, independent of that location.
    matches = re.findall(r'static const uint16_t colors\[16\]=\{([^}]+)\};', source)
    if len(matches) != 1:
        raise ValueError('Compact HUD palette declaration changed; review the compiler')
    colors = [int(value.strip(), 0) for value in matches[0].split(',')]
    if len(colors) != 16 or any(value < 0 or value > 32767 for value in colors):
        raise ValueError('Expected 16 RGB555 compact HUD colors')
    table = bytearray()
    tied = 0
    for color in range(32768):
        rgb = [color & 31, (color >> 5) & 31, (color >> 10) & 31]
        distances = [sum((rgb[shift // 5] - ((candidate >> shift) & 31)) ** 2
                         for shift in (0, 5, 10)) for candidate in colors[1:]]
        closest = min(distances)
        tied += distances.count(closest) > 1
        table.append(distances.index(closest) + 1)
    lines = ['/* Generated by tools/compile_fixed_palette.py. Do not edit.',
             ' * RGB555 opaque colors map to indices1..15; source index0 stays transparent.',
             ' * Equal squared RGB distances choose the lowest palette index. */',
             '#ifndef NATIVE_FIXED_COMPACT_PALETTE_LUT_H',
             '#define NATIVE_FIXED_COMPACT_PALETTE_LUT_H',
             '#include <stdint.h>',
             'static const uint8_t native_fixed_compact_nearest[32768]={']
    lines += [','.join(map(str, table[start:start + 64])) + ','
              for start in range(0, len(table), 64)]
    lines += ['};', '#endif', '']
    text = '\n'.join(lines)
    path = ROOT / 'generated/fixed-compact-palette-lut.h'
    if check:
        if not path.exists() or path.read_text() != text:
            raise ValueError('Stale compact palette lookup: run tools/compile_fixed_palette.py')
    elif not path.exists() or path.read_text() != text:
        path.write_text(text)
    return dict(colors=colors, entries=len(table), bytes=len(table),
                colors_with_equal_nearest_distance=tied,
                sha256=hashlib.sha256(table).hexdigest(), check=check)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    arguments = parser.parse_args()
    print(json.dumps(generate(arguments.check)))
