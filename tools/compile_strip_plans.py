#!/usr/bin/env python3
"""Compile source admission geometry once, preserving exact wrap and flip."""
from pathlib import Path
import re
import numpy as np
R=Path(__file__).resolve().parents[1]
s=(R/'generated/drawing-data.c').read_text()
def parse(name):
 t=s.split(name+'[]={',1)[1].split('};',1)[0]
 return [tuple(map(int,m.split(','))) for m in re.findall(r'\{([^{}]+)\}', '{'+t)]
maps=parse('native_draw_maps');pieces=parse('native_draw_pieces')
rows={};plans={};ids=[];x=np.arange(512)
for first,count,attr in maps:
 plan=[]
 assert count and first+count<=len(pieces)
 for flip in range(2):
  n=np.zeros(512,dtype=np.uint16)
  for _,px,py,w,h in pieces[first:first+count]:
   assert w and 0<h<=32
   start=x+((-px-17) if flip else px)
   for col in range(w):
    xx=(start+(-col*16 if flip else col*16))&511;n+=((xx<320)|(xx>=496))
  assert n.max()<256
  for phase in range(16):
   key=tuple(map(int,n[phase::16]));plan.append(rows.setdefault(key,len(rows)))
 key=tuple(plan);ids.append(plans.setdefault(key,len(plans)))
assert len(plans)<65536 and len(rows)<65536
fmt=lambda a:'{'+','.join(map(str,a))+'}'
text='/* Generated by compile_strip_plans.py; immutable native admission plans. */\n'
text+='static const uint16_t strip_plan_ids[]={'+','.join(map(str,ids))+'};\n'
text+='static const uint16_t strip_plans[][32]={'+','.join(map(fmt,plans))+'};\n'
text+='static const uint8_t strip_rows[][32]={'+','.join(map(fmt,rows))+'};\n'
(R/'generated/strip-plans.inc').write_text(text)
print(dict(maps=len(maps),plans=len(plans),rows=len(rows),bytes=len(ids)*2+len(plans)*64+len(rows)*32))
