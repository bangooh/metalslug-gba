#!/usr/bin/env python3
"""Losslessly repack the final-results orbit as two native affine BGs.

Both layers share the original 16 palette indices. Splitting the 385 unique
tiles avoids the 256 tile limit of one GBA affine layer; transparent tile zero
in the other layer makes their overlay exactly equal to the source canvas.
"""
from pathlib import Path
import hashlib
import json
import re

R = Path(__file__).resolve().parents[1]


def generate():
    source = (R / 'generated/scaled-drawing-data.c').read_text()

    def rows(name):
        body = source.split(name + '[]=', 1)[1].split(';', 1)[0]
        return [tuple(map(int, v.split(','))) for v in re.findall(r'\{([^{}]+)\}', body)]

    maps = rows('native_scaled_maps')
    chunks = rows('native_scaled_chunks')
    pixels = (R / 'generated/native-scaled-objects.4bpp').read_bytes()
    first, count = maps[5026 * 9]
    parts = chunks[first:first + count]
    x0 = min(c[1] for c in parts)
    y0 = min(c[2] for c in parts)
    canvas = bytearray(256 * 256)
    for off, x, y, w, h, shape, size in parts:
        assert 0 <= x - x0 <= 256 - w and 0 <= y - y0 <= 256 - h
        for yy in range(h):
            for xx in range(w):
                b = pixels[off + ((yy // 8) * (w // 8) + xx // 8) * 32 + (yy % 8) * 4 + xx % 8 // 2]
                value = (b >> (4 * (xx % 2))) & 15
                at = (y - y0 + yy) * 256 + x - x0 + xx
                assert not canvas[at] or canvas[at] == value or not value
                if value:
                    canvas[at] = value
    tiles = [bytes(64)]
    ids = {tiles[0]: 0}
    planes = [bytearray(1024), bytearray(1024)]
    for y in range(32):
        for x in range(32):
            tile = b''.join(canvas[(y * 8 + j) * 256 + x * 8:(y * 8 + j) * 256 + x * 8 + 8] for j in range(8))
            if tile not in ids:
                ids[tile] = len(tiles)
                tiles.append(tile)
            i = ids[tile]
            planes[i >= 256][y * 32 + x] = i if i < 256 else i - 255
    assert 256 <= len(tiles) <= 511
    banks = [b''.join(tiles[:256]), bytes(64) + b''.join(tiles[256:])]
    # Independent hardware-layout decoding: all 65,536 pixels must match.
    for y in range(256):
        for x in range(256):
            at = y // 8 * 32 + x // 8
            within = y % 8 * 8 + x % 8
            values = [banks[g][planes[g][at] * 64 + within] for g in range(2)]
            assert not (values[0] and values[1])
            assert (values[0] | values[1]) == canvas[y * 256 + x]

    def array(name, data):
        return 'static const uint8_t ' + name + '[] __attribute__((aligned(4)))={\n' + ',\n'.join(','.join(map(str, data[i:i + 32])) for i in range(0, len(data), 32)) + '\n};\n'

    output = '/* Generated by tools/build_result_affine.py; exact palette-index overlay. */\n'
    output += f'enum {{RESULT_BG_X={-x0},RESULT_BG_Y={-y0}}};\n'
    for i in range(2):
        output += array('result_bg_tiles' + str(i), banks[i]) + array('result_bg_map' + str(i), planes[i])
    (R / 'generated/result-affine.inc').write_text(output)
    report = dict(map=5026, origin=[-x0, -y0], unique_tiles=len(tiles), bytes=sum(map(len, banks)) + 2048,
                  compared_pixels=65536, pixel_sha256=hashlib.sha256(canvas).hexdigest())
    (R / 'generated/result-affine.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report))


if __name__ == '__main__':
    generate()
