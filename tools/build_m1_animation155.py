"""Compile source auto-animation into sparse eight-phase native map variants.
Keep approved base tiles/palettes and destruction transitions unchanged.
"""
import json,re,sys
from pathlib import Path
import numpy as np
from compile_m1_native_maps import body,numbers
R=Path(__file__).resolve().parents[1];G=R/'generated';D=G/'m1-cartridge'
s=(G/'scene-programs.c').read_text()
rows=[r for r in json.loads((G/'tile-video-source.json').read_text())['records'] if r['file']=='scene-programs.c'][:15]
raw=np.fromfile(G/'native-scaled-background-12x12.4bpp',np.uint8).reshape(-1,12,6)
pix=np.empty((len(raw),12,12),np.uint8);pix[:,:,::2]=raw&15;pix[:,:,1::2]=raw>>4
pals=np.array(numbers(body((G/'drawing-data.c').read_text(),'native_source_palettes')),np.uint16).reshape(-1,16)
bind=np.full(256,-1,int)
for slot,pal,flags in np.array(numbers(body((G/'session-data.c').read_text(),'session_palettes'))).reshape(-1,3):bind[slot]=pal
for slot,pal in np.array(numbers(body(s,'scene_palette_pairs'))).reshape(-1,2)[:102]:bind[slot&255]=-1 if pal==65535 else 1024+pal
pal=np.fromfile(D/'palette.bin','<u2')
colors=np.arange(32768);rgb=lambda v:np.stack([v&31,(v>>5)&31,(v>>10)&31],-1).astype(np.int32)
lut=np.argmin(((rgb(colors)[:,None]-rgb(pal[1:])[None])**2).sum(2),1)+1
baseline=json.loads((D/'animation155.json').read_text())['base_tiles'] if (D/'animation155.json').exists() else len((D/'tiles.bin').read_bytes())//64
basebytes=(D/'tiles.bin').read_bytes()[:baseline*64]; tiles=[basebytes[i:i+64] for i in range(0,len(basebytes),64)];lookup={t:i for i,t in enumerate(tiles)}
meta=[numbers(x) for x in re.findall(r'\{([^{}]+)\}',body((G/'m1-assets.c').read_text(),'m1_images'))]
base=np.fromfile(D/'maps.bin','<u2'); records={};previous={}
anchors=[(0,128),(656,352),(0,48),(1920,128),(1856,352),(1920,352),(2752,336),(2784,240),(2912,352),(3024,48),(3392,0),(3328,32),(3776,16),(3776,224),(1520,32)]
for chain in [[0,3,10,12],[1,4,5,7,8,11,13],[6,9],[2,14]]:
 active={}
 for image in chain:
  row=rows[image];cells=np.array(numbers(body(s,row['cells']))).reshape(row['width'],row['height'],2);ox,oy=[v*3//4 for v in anchors[image]]
  # Rebinding replaces the whole source rectangle, including static cells.
  active={k:v for k,v in active.items() if not (ox<=k[0]<ox+row['width']*12 and oy<=k[1]<oy+row['height']*12)}
  for x in range(row['width']):
   for y in range(row['height']):
    t,at=map(int,cells[x,y]);mask=7 if at&8 else 3 if at&4 else 0
    if not mask:continue
    variants=[]
    for phase in range(8):
     frame=phase&mask
     p=pix[((t&~mask)|frame)+((at>>4)&15)*65536,::-1 if at&2 else 1,::-1 if at&1 else 1]
     variants.append(np.where(p,lut[pals[bind[at>>8],p]&32767],0).astype(np.uint8))
    for py in range(12):
     for px in range(12):active[(ox+x*12+px,oy+y*12+py)]=[int(v[py,px]) for v in variants]
  off,w,h,*_=meta[image];bytile={}
  for (x,y),v in active.items():
   if not(0<=x<w*8 and 0<=y<h*8):continue
   pos=off+(y//8)*w+x//8
   if pos not in bytile:bytile[pos]=np.tile(np.frombuffer(tiles[int(base[pos])],np.uint8).reshape(8,8),(8,1,1)).copy()
   bytile[pos][:,y%8,x%8]=v
  if image<9 or image>13:continue
  for pos,variants in bytile.items():
   ids=[]
   for v in variants:
    key=v.tobytes()
    if key not in lookup:lookup[key]=len(tiles);tiles.append(key)
    ids.append(lookup[key])
   if len(set(ids))>1:records[pos]=[int(base[pos]),*ids]
print('base',len(basebytes)//64,'total',len(tiles),'records',len(records),flush=True)
assert len(tiles)<65535
(D/'tiles.bin').write_bytes(b''.join(tiles));(D/'opacity.bin').write_bytes(np.packbits(np.frombuffer(b''.join(tiles),np.uint8).reshape(-1,8)>0,axis=1,bitorder='little').tobytes())
p=G/'m1-assets.h';p.write_text(re.sub(r'M1_TILE_COUNT=\d+',f'M1_TILE_COUNT={len(tiles)}',p.read_text()))
text='/* Generated by build_m1_animation155.py; eight authored source phases. */\nstruct M1Animation155 {uint32_t offset;uint16_t base,phase[8];};\nstatic const struct M1Animation155 m1_animation155[]={\n'
text+='\n'.join('{%d,%d,{%s}},'%(pos,v[0],','.join(map(str,v[1:]))) for pos,v in sorted(records.items()))+'\n};\n'
(G/'m1-animation155.h').write_text(text)
(D/'animation155.json').write_text(json.dumps({'base_tiles':len(basebytes)//64,'total_tiles':len(tiles),'animated_map_cells':len(records),'phases':8},indent=2))
